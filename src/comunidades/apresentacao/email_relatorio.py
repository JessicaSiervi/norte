"""O e-mail de um relatório (botão "Enviar"): o PDF anexo, o título, o código de verificação e quem gerou.

Só para endereços do domínio da empresa (a API confere). Nada de UC, coordenada ou nome de cliente:
o relatório só tem agregados. Todo texto do HTML passa por html.escape. No idioma de quem enviou (Fase K),
com a versão em texto simples e a em HTML.
"""

import html
from email.message import EmailMessage
from email.utils import formatdate, make_msgid

TEXTOS = {
    "pt-BR": {"gerado": "Gerado por", "codigo": "Código de verificação",
              "anexo": "O PDF vai anexo; a segunda via fica guardada no Norte, com o mesmo SHA-256."},
    "en": {"gerado": "Generated by", "codigo": "Verification code",
           "anexo": "The PDF is attached; the second copy is stored in Norte, with the same SHA-256."},
    "es": {"gerado": "Generado por", "codigo": "Código de verificación",
           "anexo": "El PDF va adjunto; la segunda copia queda guardada en Norte, con el mismo SHA-256."},
}


def mensagem(*, remetente: str, destinos: list[str], titulo: str, codigo: str, gerado_por: str, empresa: str,
             pdf: tuple[str, bytes], aviso_ficticio: str, idioma: str = "pt-BR") -> EmailMessage:
    i = idioma if idioma in TEXTOS else "pt-BR"
    x = TEXTOS[i]
    m = EmailMessage()
    m["From"], m["To"] = remetente, ", ".join(destinos)
    m["Subject"] = f"Norte: {titulo} ({codigo})"
    m["Content-Language"] = i
    m["Date"] = formatdate(localtime=False)
    m["Message-ID"] = make_msgid(domain=remetente.rsplit("@", 1)[-1].strip("> ") or "farol.example")
    m.set_content(f"{empresa}: {titulo}.\n\n{x['gerado']} {gerado_por}. {x['codigo']}: {codigo}.\n{x['anexo']}\n\n{aviso_ficticio}\n")
    e = html.escape
    m.add_alternative(f"""<!doctype html><html lang="{i}"><body style="font-family:Arial,sans-serif;color:#0B1B2B">
<p><b>{e(empresa)}</b>: {e(titulo)}.</p><p>{e(x['gerado'])} {e(gerado_por)}. {e(x['codigo'])}: <b>{e(codigo)}</b>.</p>
<p>{e(x['anexo'])}</p>
<p style="color:#4A5560;font-size:13px">{e(aviso_ficticio)}</p></body></html>""", subtype="html")
    m.add_attachment(pdf[1], maintype="application", subtype="pdf", filename=pdf[0])
    return m
